"""Run tap.python~'s runtime tests inside a real Max (plan 6.1, 6.4).

    python3 runtime-tests/run.py                     # everything: both sessions below
    python3 runtime-tests/run.py --session main      # just the tests with the runtime installed
    python3 runtime-tests/run.py --only reload -v    # the main tests whose names contain "reload"
    python3 runtime-tests/run.py --session soak      # the hour-long soak (plan 6.2), on its own
    python3 runtime-tests/run.py --session perf      # Max's CPU meter under load (plan 6.3)

Needs macOS with Max 9, the external built (cmake --build build), the runtime installed
(scripts/install-runtime.sh), and the package in Max's Packages folder as "PythonTap". It launches
Max itself, drives it over OSC through the max-test harness (the runtime-tests/max-test submodule),
and quits it when done, so do not run it while Max is open. Two sessions:

    without-runtime  support/ is moved aside before Max starts: the object must still load and
                     say what is missing (4.2). support/ is then put back while Max runs, and a
                     new object must still say so — on macOS the weak binding is fixed when the
                     external loads, so a runtime installed later needs a restart (by design).
    main             the patchers in runtime-tests/patchers/, generated by make_patchers.py.
    soak             (only when asked for) an hour of audio, saves every second and a sample-rate
                     change; Max's memory is sampled every minute, and a summary of it, the
                     reloads, Max's DSP CPU and Python's object count goes to logs/soak.summary.
    perf             (only when asked for) Max's own DSP CPU meter with instances of the shipped
                     examples, averaged into logs/perf.json (scripts/update-perf-docs.py --max).

It installs the harness into Packages as max-test (a copy: Max loads extensions only from a real
folder; it stays installed), links runtime-tests/ in as PythonTap-runtime-tests for the run, and
copies the fixtures in runtime-tests/python/ into python/, where tap.python~ looks for class files;
it removes the link and the copies afterwards, and always puts support/ back. Results come from the
harness's SQLite database; the exit status is non-zero if anything failed. See README.md here.
"""

